"""Run the toolkit on the PubChem AID 411 subset; compare with the depositor's own Hill fits.

Writes results/pubchem_summary.json, docs/example_report.html and docs/example_report.pdf.
"""
import json, collections
import numpy as np
from doseresponse import analyze
from doseresponse.io import read_long_csv
from doseresponse.report import html_report, pdf_report

data = read_long_csv("data/pubchem_aid411_subset.csv", "sid", "conc_uM", "response_pct")
res = {}
for i, (sid, (c, r, row)) in enumerate(data.items()):
    res[sid] = (analyze(c, r, unit="uM", n_boot=300, seed=i), row)

summ = {"n_compounds": len(res)}
summ["status_by_outcome"] = {}
for oc in ("Active", "Inconclusive", "Inactive"):
    cnt = collections.Counter(A.status for A, row in res.values() if row["outcome"] == oc)
    summ["status_by_outcome"][oc] = dict(cnt)
flagc = collections.Counter(c for A, _ in res.values() for c, _, _ in A.flags)
summ["flag_counts"] = dict(flagc)

# agreement with depositor logAC50 (M) where both report a value
def fin(v):
    try:
        return np.isfinite(float(v))
    except ValueError:
        return False

pairs = []
for sid, (A, row) in res.items():
    try:
        d = float(row["depositor_logac50_M"]) + 6.0   # -> log10 uM
    except ValueError:
        continue
    if A.logic50 is not None and np.isfinite(d):
        pairs.append((sid, A.logic50, d, row["outcome"], A.status))
diff = np.array([p[1] - p[2] for p in pairs])
summ["depositor_comparison"] = {} if len(pairs) < 3 else {
    "n_pairs": len(pairs),
    "median_diff_log10": float(np.median(diff)),
    "median_abs_diff_log10": float(np.median(np.abs(diff))),
    "frac_within_0.3_log10": float(np.mean(np.abs(diff) <= 0.3)),
    "pearson_r": float(np.corrcoef([p[1] for p in pairs], [p[2] for p in pairs])[0, 1]),
}
okp = [p for p in pairs if p[4] == "ok"]
if len(okp) >= 3 and pairs:
    d2 = np.array([p[1] - p[2] for p in okp])
    summ["depositor_comparison"]["ok_only"] = {"n": len(okp), "median_abs_diff_log10": float(np.median(np.abs(d2))),
                                                "frac_within_0.3_log10": float(np.mean(np.abs(d2) <= 0.3))}
# depositor-reported AC50 for curves we call undefined
und_dep = [sid for sid, (A, row) in res.items() if A.ic50 is None and fin(row["depositor_logac50_M"])]
summ["undefined_but_depositor_reports_ac50"] = len(und_dep)
# CI quality
ws = [A.logic50_ci[1] - A.logic50_ci[0] for A, _ in res.values() if A.logic50_ci]
summ["median_ci_width_log10_reported"] = float(np.median(ws)) if ws else None
json.dump(summ, open("results/pubchem_summary.json", "w"), indent=1)
print(json.dumps(summ, indent=1))

# example report: first of each category
pick = []
def first(pred, k):
    got = [sid for sid, (A, row) in res.items() if pred(A, row)][:k]
    pick.extend(got)
first(lambda A, r: A.status == "ok" and r["outcome"] == "Active", 3)
first(lambda A, r: A.status == "warn", 3)
first(lambda A, r: A.status == "undefined" and {c for c, _, _ in A.flags} & {"IC50_NOT_BRACKETED", "IC50_CI_NOT_BRACKETED", "PLATEAU_UNIDENTIFIED"}, 3)
first(lambda A, r: A.status == "undefined" and "NO_ACTIVITY" in {c for c, _, _ in A.flags}, 2)
items = [(f"AID 411 SID {sid} ({res[sid][1]['outcome']})", res[sid][0]) for sid in pick]
intro = ("<p>Example report generated by <code>experiments/pubchem_aid411.py</code> from a fixed random subset of PubChem BioAssay "
         "AID 411 (qHTS firefly luciferase inhibition, NCGC). Selected curves are the first of each QC category, not a random sample. "
         "Counts over all 300 compounds are in <code>results/pubchem_summary.json</code>. "
         "Not done: no replicate-level error model, no outlier removal, no multiple-testing treatment.</p>")
open("docs/example_report.html", "w").write(html_report(items, "Dose–response report: PubChem AID 411 examples", intro))
pdf_report(items, "docs/example_report.pdf", "PubChem AID 411 examples")
